/**
 * محاسبه کارمزد پلکانی خدمات و معامله امن بازار بر اساس قیمت محصول
 * هر چه قیمت کالا بالاتر باشد درصد و مبلغ کارمزد بیشتر می‌شود
 * - زیر ۵۰۰ هزار ت: ۱۰,۰۰۰ تومان
 * - بین ۵۰۰ هزار تا ۲ میلیون ت: ۲۰,۰۰۰ تومان
 * - بین ۲ تا ۱۰ میلیون ت: ۴۵,۰۰۰ تومان
 * - بین ۱۰ تا ۳۰ میلیون ت: ۸۵,۰۰۰ تومان
 * - بالای ۳۰ میلیون ت: ۱۵۰,۰۰۰ تومان
 */
export const calculateMarketplaceCommission = (price: number): number => {
  if (!price || price <= 0) return 0;
  if (price < 500000) return 10000;
  if (price < 2000000) return 20000;
  if (price < 10000000) return 45000;
  if (price < 30000000) return 85000;
  return 150000;
};

