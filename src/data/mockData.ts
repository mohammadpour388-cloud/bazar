// Helper to convert Persian/Arabic numerals to standard English digits
export function toEnglishDigits(str: string): string {
  if (!str) return '';
  return str
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 1776))
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 1632));
}

// Helper to format number to Persian digits
export function toPersianDigits(num: number | string): string {
  const farsiDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return num
    .toString()
    .replace(/\d/g, (x) => farsiDigits[parseInt(x, 10)]);
}

// Helper to format price with commas and Persian numerals
export function formatToman(amount: number): string {
  const formatted = amount.toLocaleString('en-US');
  return toPersianDigits(formatted);
}

// Convert numbers to Persian text words (supports billions, millions, thousands smoothly)
export function numberToPersianWords(amount: number): string {
  if (amount <= 0 || isNaN(amount)) return 'قیمت توافقی';

  const ones = ['', 'یک', 'دو', 'سه', 'چهار', 'پنج', 'شش', 'هفت', 'هشت', 'نه'];
  const teens = ['ده', 'یازده', 'دوازده', 'سیزده', 'چهارده', 'پانزده', 'شانزده', 'هفده', 'هجده', 'نوزده'];
  const tens = ['', '', 'بیست', 'سی', 'چهل', 'پنجاه', 'شصت', 'هفتاد', 'هشتاد', 'نود'];
  const hundreds = ['', 'صد', 'دویست', 'سیصد', 'چهارصد', 'پانصد', 'ششصد', 'هفتصد', 'هشتصد', 'نهصد'];

  function convertThreeDigits(num: number): string {
    const parts: string[] = [];
    const h = Math.floor(num / 100);
    const rem = num % 100;
    if (h > 0) parts.push(hundreds[h]);
    if (rem >= 10 && rem <= 19) {
      parts.push(teens[rem - 10]);
    } else {
      const t = Math.floor(rem / 10);
      const o = rem % 10;
      if (t > 0) parts.push(tens[t]);
      if (o > 0) parts.push(ones[o]);
    }
    return parts.join(' و ');
  }

  const hemmats = Math.floor(amount / 1000000000000);
  const billions = Math.floor((amount % 1000000000000) / 1000000000);
  const millions = Math.floor((amount % 1000000000) / 1000000);
  const thousands = Math.floor((amount % 1000000) / 1000);
  const remaining = Math.floor(amount % 1000);

  const sections: string[] = [];
  if (hemmats > 0) {
    sections.push(`${convertThreeDigits(hemmats)} هزار میلیارد (همت)`);
  }
  if (billions > 0) {
    sections.push(`${convertThreeDigits(billions)} میلیارد`);
  }
  if (millions > 0) {
    sections.push(`${convertThreeDigits(millions)} میلیون`);
  }
  if (thousands > 0) {
    sections.push(`${convertThreeDigits(thousands)} هزار`);
  }
  if (remaining > 0) {
    sections.push(convertThreeDigits(remaining));
  }

  return sections.length > 0 ? `${sections.join(' و ')} تومان` : `${toPersianDigits(amount)} تومان`;
}

